#!/usr/bin/env python3
"""json_to_ts.py: infer exported TypeScript interfaces from a JSON sample.

Command:
    python -I scripts/json_to_ts.py <input-file> <output-file.ts> [--root-name NAME]

Input: one JSON object, or a non-empty JSON array whose items are all objects.
Output: a new .ts file, created with exclusive mode. Existing paths are refused,
and the input file is never written.
stdout: one JSON summary line. stderr: one JSON error line when exit code is 2.
Exit codes: 0 no findings; 1 findings (the .ts file is still written);
2 usage or input error (no file written).
Stdlib only. No network, no subprocess, no eval or exec. The input is read only.
"""
import argparse
import json
import os
import re
import sys

MAX_BYTES = 2 * 1024 * 1024
DEFAULT_ROOT = "Root"
HEADER = ("// Generated by json_to_ts.py from a JSON sample. "
          "Check every finding and every optional marker against the live source before use.")
IDENT_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
PRIMITIVES = ("string", "number", "boolean")


class InputError(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code
        self.message = message


def fail(code, message):
    raise InputError(code, message)


def emit_error(code, message):
    sys.stderr.write(json.dumps({"error": code, "message": message}) + "\n")
    sys.exit(2)


class Parser(argparse.ArgumentParser):
    def error(self, message):
        emit_error("USAGE", message)


class Node:
    """One schema position. Every sample value that reaches this position is recorded here."""

    def __init__(self):
        self.kinds = set()    # subset of: string, number, boolean, null, object, array
        self.props = {}       # key -> Node, in first-seen order
        self.presence = {}    # key -> number of object values at this position that contain the key
        self.obj_count = 0    # number of object values at this position
        self.elem = None      # Node for array items; stays None while every array is empty


def add(node, value):
    if value is None:
        node.kinds.add("null")
    elif isinstance(value, bool):
        node.kinds.add("boolean")
    elif isinstance(value, (int, float)):
        node.kinds.add("number")
    elif isinstance(value, str):
        node.kinds.add("string")
    elif isinstance(value, dict):
        node.kinds.add("object")
        node.obj_count += 1
        for key, child in value.items():
            if key not in node.props:
                node.props[key] = Node()
            node.presence[key] = node.presence.get(key, 0) + 1
            add(node.props[key], child)
    elif isinstance(value, list):
        node.kinds.add("array")
        for item in value:
            if node.elem is None:
                node.elem = Node()
            add(node.elem, item)
    else:
        fail("INVALID_JSON", "unsupported value in input")


class Ctx:
    def __init__(self):
        self.decls = []
        self.used = set()
        self.findings = []
        self.interfaces = 0
        self.optional = 0

    def note(self, code, path):
        self.findings.append({"code": code, "path": path})

    def allocate(self, hint, path):
        base = pascal(hint)
        name, n = base, 2
        while name in self.used:
            name = f"{base}{n}"
            n += 1
        if name != base:
            self.note("NAME_COLLISION", path)
        self.used.add(name)
        return name


def pascal(text):
    out = "".join(part[:1].upper() + part[1:]
                  for part in re.split(r"[^A-Za-z0-9]+", text) if part)
    if not out:
        return "Item"
    if out[0].isdigit():
        return "T" + out
    return out


def singular(word):
    if len(word) > 3 and word.endswith("ies"):
        return word[:-3] + "y"
    if len(word) > 2 and word.endswith("s") and not word.endswith(("ss", "us", "is")):
        return word[:-1]
    return word


def prop_name(key):
    return key if IDENT_RE.match(key) else json.dumps(key, ensure_ascii=False)


def key_path(key):
    return "." + key if IDENT_RE.match(key) else "[" + json.dumps(key) + "]"


def declare(node, hint, path, ctx):
    name = ctx.allocate(hint, path)
    ctx.interfaces += 1
    slot = len(ctx.decls)
    ctx.decls.append("")
    if not node.props:
        ctx.decls[slot] = f"export interface {name} {{}}"
        return name
    lines = []
    for key, child in node.props.items():
        optional = node.presence[key] < node.obj_count
        if optional:
            ctx.optional += 1
        child_type = render(child, key, path + key_path(key), ctx)
        marker = "?" if optional else ""
        lines.append(f"  {prop_name(key)}{marker}: {child_type};")
    ctx.decls[slot] = f"export interface {name} {{\n" + "\n".join(lines) + "\n}"
    return name


def render_array(node, hint, path, ctx):
    if node.elem is None:
        ctx.note("EMPTY_ARRAY", path)
        return "unknown[]"
    elem_type = render(node.elem, singular(hint), path + "[]", ctx)
    if " | " in elem_type:
        return f"({elem_type})[]"
    return f"{elem_type}[]"


def render(node, hint, path, ctx):
    parts = [kind for kind in PRIMITIVES if kind in node.kinds]
    non_null = len(parts) + ("object" in node.kinds) + ("array" in node.kinds)
    if "object" in node.kinds:
        parts.append(declare(node, hint, path, ctx))
    if "array" in node.kinds:
        parts.append(render_array(node, hint, path, ctx))
    if non_null > 1:
        ctx.note("MIXED_TYPES", path)
    if "null" in node.kinds:
        if non_null == 0:
            ctx.note("NULL_ONLY", path)
            return "null"
        parts.append("null")
    return " | ".join(parts)


def check_output_path(path):
    if not path.endswith(".ts"):
        fail("OUTPUT_EXTENSION", "output file name must end in .ts")
    if os.path.exists(path):
        fail("OUTPUT_EXISTS", "output path already exists; choose a new file name")
    parent = os.path.dirname(os.path.abspath(path))
    if not os.path.isdir(parent):
        fail("OUTPUT_DIR_MISSING", "output directory does not exist")


def _reject_constant(name):
    raise ValueError("non-standard constant " + name)


def read_input(path):
    if not os.path.isfile(path):
        fail("INPUT_NOT_FOUND", "input file not found")
    try:
        if os.path.getsize(path) > MAX_BYTES:
            fail("INPUT_TOO_LARGE", "input is larger than 2 MB")
        with open(path, "rb") as handle:
            raw = handle.read(MAX_BYTES + 1)
    except OSError:
        fail("INPUT_UNREADABLE", "input file could not be read")
    if len(raw) > MAX_BYTES:
        fail("INPUT_TOO_LARGE", "input is larger than 2 MB")
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        fail("INVALID_UTF8", "input is not valid UTF-8")
    try:
        return json.loads(text, parse_constant=_reject_constant)
    except RecursionError:
        fail("TOO_DEEP", "nesting is too deep to process")
    except ValueError:
        fail("INVALID_JSON", "input is not valid JSON")


def check_root(data):
    if isinstance(data, dict):
        return
    if not isinstance(data, list):
        fail("ROOT_NOT_OBJECT", "root must be a JSON object or an array of objects")
    if not data:
        fail("EMPTY_ROOT_ARRAY", "root array has no items to infer from")
    if not all(isinstance(item, dict) for item in data):
        fail("ROOT_NOT_OBJECTS", "every root array item must be a JSON object")


def generate(data, root_name):
    ctx = Ctx()
    root = Node()
    if isinstance(data, dict):
        add(root, data)
    else:
        for item in data:
            add(root, item)
    name = render(root, root_name, "$", ctx)
    if isinstance(data, list):
        ctx.decls.append(f"export type {name}List = {name}[];")
    text = "\n\n".join([HEADER] + ctx.decls) + "\n"
    return text, ctx


def write_output(path, text):
    try:
        with open(path, "x", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    except FileExistsError:
        fail("OUTPUT_EXISTS", "output path already exists; choose a new file name")
    except OSError:
        fail("OUTPUT_WRITE_FAILED", "could not create the output file")


def main(argv=None):
    parser = Parser(description="Infer exported TypeScript interfaces from a JSON sample.")
    parser.add_argument("input_file")
    parser.add_argument("output_file")
    parser.add_argument("--root-name", default=DEFAULT_ROOT)
    args = parser.parse_args(argv)
    try:
        if not IDENT_RE.match(args.root_name):
            fail("USAGE", "--root-name must be a plain identifier")
        check_output_path(args.output_file)
        data = read_input(args.input_file)
        check_root(data)
        text, ctx = generate(data, args.root_name)
        write_output(args.output_file, text)
    except InputError as exc:
        emit_error(exc.code, exc.message)
    except RecursionError:
        emit_error("TOO_DEEP", "nesting is too deep to process")
    summary = {
        "status": "findings" if ctx.findings else "ok",
        "interfaces": ctx.interfaces,
        "optional_properties": ctx.optional,
        "findings": ctx.findings,
    }
    print(json.dumps(summary))
    return 1 if ctx.findings else 0


if __name__ == "__main__":
    sys.exit(main())
