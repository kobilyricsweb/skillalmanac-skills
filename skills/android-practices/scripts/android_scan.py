#!/usr/bin/env python3
"""Scan Kotlin source files for six documented Android anti-patterns.

Usage:
    python android_scan.py <file-or-folder> [<file-or-folder> ...]

Reads `.kt` files only (never `.kts`, never Java). Writes nothing. Uses no network
and no subprocess. Prints one JSON object on stdout (contract in SKILL.md).

Exit codes:
    0  scan finished, no finding with severity "warn"
    1  scan finished, at least one "warn"
    2  no readable .kt file was found (the reason is printed on stderr)

How it works: comments and string contents are blanked (same length, so offsets and
line numbers stay valid), then regular expressions run on the blanked text. This is
a heuristic reader, not the Kotlin compiler. A finding is a place to look, not a
proven defect. Do not edit this file to make a finding disappear.
"""
import bisect
import json
import os
import re
import sys

SCHEMA_VERSION = 1
TOOL = "android_scan"

# Files above this size are skipped: a 1 MB .kt file is almost certainly generated.
MAX_BYTES = 1000000
# Working values, not measured: info from 4 "!!" per file, warn from 8 and at least
# 2 per 100 code lines (same numbers as the sibling flutter scanner, for consistency).
BANG_INFO = 4
BANG_WARN = 8
BANG_DENSITY = 2.0
# A BuildConfig.DEBUG guard must sit on the Log line or within this many lines above.
GUARD_WINDOW = 4

SKIP_DIRS = {"build", ".gradle", ".git", ".idea", "node_modules", "generated"}
TEST_DIRS = {"test", "androidTest", "commonTest", "testFixtures", "sharedTest", "jvmTest"}
TEST_NAME = re.compile(r"(Test|Tests)\.kt$")

SPECIAL = re.compile(r"//|/\*|\"\"\"|\"|'")
CHAR_LIT = re.compile(r"'(?:\\[^']*|[^'\\])'")

GLOBAL_SCOPE = re.compile(r"\bGlobalScope\b")
RUN_BLOCKING = re.compile(r"\brunBlocking\b")
UI_LIKE = re.compile(
    r"@Composable|\b(?:ComponentActivity|AppCompatActivity|FragmentActivity|Activity|"
    r"Fragment|DialogFragment|ViewModel|AndroidViewModel|Service|BroadcastReceiver)\b")
MAIN_FUN = re.compile(r"\bfun\s+main\s*\(")
LOG_DV = re.compile(r"\bLog\.(d|v)\s*\(")
LOG_GUARD = re.compile(r"BuildConfig\.DEBUG|\bisDebuggable\b")
PRINTLN = re.compile(r"\bprintln\s*\(|\.printStackTrace\s*\(")
FUN_RE = re.compile(r"\bfun\b")
TEXT_CALL = re.compile(r"\bText\s*\(\s*(?:text\s*=\s*)?(?=\")")
KW_ASSIGN = re.compile(r"\b(contentDescription|text|label|placeholder|title)\s*=\s*(?=\")")
OBJ_HEADER = re.compile(r"\bcompanion\s+object\b|\bobject\s+[A-Za-z_]\w*")
LEAK_PROP = re.compile(
    r"^\s*(?:(?:private|internal|public|protected)\s+)?(?:@\w+(?:\([^)]*\))?\s+)*"
    r"(?:lateinit\s+)?(?:var|val)\s+(\w+)\s*:\s*"
    r"((?:android\.\w+\.)*(?:Context|\w*Activity|\w*Fragment|\w*View))\??\s*(?:=|$|by\b)")
LETTER = re.compile(r"[A-Za-zÀ-￿]")
INTERP = re.compile(r"\$\{[^}]*\}|\$\w+")

LIMITS = [
    "Regex reading of Kotlin, not the compiler: no types, no imports resolved, no data flow.",
    "Only .kt files are read; .kts, Java and XML layouts are not.",
    "Test source sets and generated files are skipped and listed under skipped.",
    "hardcoded-string-in-composable sees only block-bodied @Composable functions (not "
    "expression bodies), skips @Preview functions, and knows only Text(...), text=, "
    "contentDescription=, label=, placeholder= and title= with a string literal.",
    "log-in-release accepts a BuildConfig.DEBUG guard within 4 lines above; it cannot see "
    "R8 rules that strip Log calls, Timber trees, or a wrapper class.",
    "context-leak-static checks property declarations with a direct type in object, "
    "companion object and top level; generics, inferred types and indirect holders are missed.",
    "runblocking-in-ui treats a file as UI code when it mentions @Composable, an Activity, "
    "Fragment, ViewModel, Service or BroadcastReceiver; other files get info, and files with "
    "fun main are not checked.",
    "Thresholds (4 and 8 not-null assertions, 2 per 100 code lines) are working values.",
]

RULE_TEXT = {
    "global-scope": (
        "GlobalScope coroutines outlive every screen and are never cancelled with it.",
        "Use viewModelScope, lifecycleScope, rememberCoroutineScope, or an injected "
        "application scope with a SupervisorJob."),
    "runblocking-in-ui": (
        "runBlocking parks the calling thread; on the main thread this freezes input and can "
        "trigger an ANR.",
        "Make the caller a suspend function or launch in a lifecycle-aware scope; keep "
        "runBlocking to main() and tests."),
    "null-assertion-density": (
        "Many !! operators are many possible NullPointerExceptions in production.",
        "Use safe calls, requireNotNull with a message, early return, or make the type "
        "non-null at the boundary."),
    "log-in-release": (
        "Debug logging left unguarded ships to users and can leak data into logcat.",
        "Guard with BuildConfig.DEBUG, route through a debug-only logging tree, or delete it."),
    "hardcoded-string-in-composable": (
        "User-visible literal inside a Composable cannot be translated or reviewed in one place.",
        "Move it to strings.xml and read it with stringResource(R.string.name)."),
    "context-leak-static": (
        "A static holder of a Context, Activity, Fragment or View keeps it alive after it is "
        "destroyed.",
        "Pass the Context as a parameter, inject the application context, or hold a "
        "WeakReference; never store an Activity or View in an object."),
}


def blank_source(src):
    """Return src with comments blanked and string or char contents replaced by '_'."""
    out = list(src)
    n = len(src)

    def fill(a, b, ch):
        for k in range(a, b):
            if out[k] not in "\r\n":
                out[k] = ch

    i = 0
    while i < n:
        m = SPECIAL.search(src, i)
        if not m:
            break
        s = m.start()
        tok = m.group(0)
        if tok == "//":
            j = src.find("\n", s)
            j = n if j < 0 else j
            fill(s, j, " ")
            i = j
        elif tok == "/*":
            j, depth = s + 2, 1
            while j < n and depth:
                if src.startswith("/*", j):
                    depth += 1
                    j += 2
                elif src.startswith("*/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            fill(s, j, " ")
            i = j
        elif tok == '"""':
            j = src.find('"""', s + 3)
            if j < 0:
                fill(s + 3, n, "_")
                i = n
            else:
                fill(s + 3, j, "_")
                i = j + 3
        elif tok == '"':
            j, depth = s + 1, 0
            while j < n:
                c = src[j]
                if depth == 0:
                    if c == "\\":
                        j += 2
                        continue
                    if c == '"' or c == "\n":
                        break
                    if c == "$" and src.startswith("{", j + 1):
                        depth = 1
                        j += 2
                        continue
                else:
                    if c == "{":
                        depth += 1
                    elif c == "}":
                        depth -= 1
                    elif c == '"':
                        k = j + 1
                        while k < n and src[k] != '"' and src[k] != "\n":
                            k += 2 if src[k] == "\\" else 1
                        j = k
                j += 1
            j = min(j, n)
            fill(s + 1, j, "_")
            i = j + 1
        else:
            cm = CHAR_LIT.match(src, s)
            if cm:
                fill(s + 1, cm.end() - 1, "_")
                i = cm.end()
            else:
                i = s + 1
    return "".join(out)


def match_close(text, open_idx, open_ch, close_ch):
    """Index of the bracket closing the one at open_idx, or -1."""
    depth = 0
    for j in range(open_idx, len(text)):
        c = text[j]
        if c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
            if depth == 0:
                return j
    return -1


def composable_bodies(masked):
    """Return (start, end) offsets of block bodies of @Composable, non-@Preview functions."""
    bodies = []
    prev_end = 0
    for m in FUN_RE.finditer(masked):
        s = m.start()
        if re.match(r"\s+interface\b", masked[m.end():m.end() + 14]):
            continue
        cut = max(masked.rfind("{", 0, s), masked.rfind("}", 0, s), masked.rfind(";", 0, s), prev_end)
        region = masked[cut + 1 if cut >= 0 else 0:s]
        prev_end = m.end()
        if "@Composable" not in region or re.search(r"@Preview\w*", region):
            continue
        p = masked.find("(", m.end())
        if p < 0:
            continue
        j = match_close(masked, p, "(", ")")
        if j < 0:
            continue
        seg = masked[j + 1:j + 201]
        sm = re.search(r"[{=]", seg)
        if not sm or sm.group(0) != "{" or FUN_RE.search(seg[:sm.start()]) or "}" in seg[:sm.start()]:
            continue
        b0 = j + 1 + sm.start()
        b1 = match_close(masked, b0, "{", "}")
        if b1 > 0:
            bodies.append((b0, b1))
    return bodies


def is_test_path(parts):
    return any(p in TEST_DIRS for p in parts[:-1]) or bool(TEST_NAME.search(parts[-1]))


def is_generated(raw):
    head = raw[:400].lower()
    return "generated by" in head or "do not edit" in head or "@generated" in head


def scan_text(raw, parts):
    """Return a list of finding dicts (without 'file') for one file."""
    masked = blank_source(raw)
    starts = [0]
    for m in re.finditer("\n", masked):
        starts.append(m.end())
    mlines = masked.split("\n")
    rlines = raw.split("\n")

    def line_of(off):
        return bisect.bisect_right(starts, off)

    def raw_line(ln):
        return rlines[ln - 1].strip()[:120] if 0 < ln <= len(rlines) else ""

    found = []

    def add(rule, line, sev, conf, match=None):
        why, fix = RULE_TEXT[rule]
        found.append({"line": line, "rule": rule, "severity": sev, "confidence": conf,
                      "match": raw_line(line) if match is None else match, "why": why, "fix": fix})

    def is_import(ln):
        return mlines[ln - 1].lstrip().startswith(("import ", "package "))

    ui_like = bool(UI_LIKE.search(masked))
    has_main = bool(MAIN_FUN.search(masked))
    in_debug_set = "debug" in parts[:-1]

    for m in GLOBAL_SCOPE.finditer(masked):
        ln = line_of(m.start())
        if not is_import(ln):
            add("global-scope", ln, "warn", "high")

    for m in RUN_BLOCKING.finditer(masked):
        ln = line_of(m.start())
        if is_import(ln):
            continue
        if ui_like:
            add("runblocking-in-ui", ln, "warn", "high")
        elif not has_main:
            add("runblocking-in-ui", ln, "info", "medium")

    bangs = [m.start() for m in re.finditer(r"!!", masked)]
    code_lines = sum(1 for t in mlines if t.strip())
    if len(bangs) >= BANG_INFO and code_lines:
        density = len(bangs) * 100.0 / code_lines
        sev = "warn" if len(bangs) >= BANG_WARN and density >= BANG_DENSITY else "info"
        first = line_of(bangs[0])
        add("null-assertion-density", first, sev, "high",
            "%d !! in %d code lines (first at line %d)" % (len(bangs), code_lines, first))

    if not in_debug_set:
        for m in LOG_DV.finditer(masked):
            ln = line_of(m.start())
            window = mlines[max(0, ln - 1 - GUARD_WINDOW):ln]
            if not LOG_GUARD.search("\n".join(window)):
                add("log-in-release", ln, "warn", "high")
        if not has_main:
            for m in PRINTLN.finditer(masked):
                add("log-in-release", line_of(m.start()), "info", "medium")

    bodies = composable_bodies(masked)
    if bodies:
        seen = set()
        hits = [(m.end(), "Text", None) for m in TEXT_CALL.finditer(masked)]
        hits += [(m.end(), "kw", m.group(1)) for m in KW_ASSIGN.finditer(masked)]
        for q, kind, name in sorted(hits):
            if q in seen or not any(a <= q < b for a, b in bodies):
                continue
            seen.add(q)
            if masked.startswith('"""', q):
                close = masked.find('"""', q + 3)
                content = raw[q + 3:close] if close >= 0 else ""
            else:
                close = masked.find('"', q + 1)
                content = raw[q + 1:close] if close >= 0 else ""
            if close < 0 or not LETTER.search(INTERP.sub("", content)):
                continue
            conf = "high" if kind == "Text" or name == "contentDescription" else "medium"
            add("hardcoded-string-in-composable", line_of(q), "info", conf)

    stack = []
    for idx, text in enumerate(mlines):
        text = text.rstrip("\r")
        ln = idx + 1
        mp = LEAK_PROP.match(text)
        if mp and (not stack or stack[-1] == "object"):
            tname = mp.group(2).split(".")[-1]
            where = "top-level" if not stack else "object"
            add("context-leak-static", ln, "warn", "medium" if tname == "Context" else "high",
                "%s property '%s: %s'" % (where, mp.group(1), tname))
        seg = 0
        for pos, ch in enumerate(text):
            if ch == "{":
                header = text[seg:pos]
                if not header.strip() and idx > 0 and seg == 0:
                    header = mlines[idx - 1]
                stack.append("object" if OBJ_HEADER.search(header) else "other")
                seg = pos + 1
            elif ch == "}":
                if stack:
                    stack.pop()
                seg = pos + 1
    return found


def read_file(path):
    """Return (text, None) or (None, reason)."""
    try:
        size = os.path.getsize(path)
        if size > MAX_BYTES:
            return None, "larger than 1 MB"
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError as exc:
        return None, "unreadable: %s" % exc.strerror
    if b"\x00" in data:
        return None, "binary content"
    try:
        return data.decode("utf-8-sig"), None
    except UnicodeDecodeError:
        return data.decode("latin-1"), None


def display(path):
    p = path.replace(os.sep, "/")
    return p[2:] if p.startswith("./") else p


def collect(args, skipped):
    """Return a list of (display_path, real_path, parts_for_classification)."""
    files, seen = [], set()

    def push(disp, real, parts):
        key = os.path.realpath(real)
        if key not in seen:
            seen.add(key)
            files.append((display(disp), real, parts))

    for arg in args:
        if os.path.isfile(arg):
            if arg.endswith(".kt"):
                tail = os.path.normpath(arg).split(os.sep)[-3:]
                push(arg, arg, tail)
            else:
                skipped.append({"file": display(arg), "reason": "not a .kt file"})
        elif os.path.isdir(arg):
            for root, dirs, names in os.walk(arg):
                dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
                for name in sorted(names):
                    if name.endswith(".kt"):
                        real = os.path.join(root, name)
                        rel = os.path.relpath(real, arg).split(os.sep)
                        push(os.path.join(arg, os.path.relpath(real, arg)), real, rel)
        else:
            skipped.append({"file": display(arg), "reason": "path not found"})
    return files


def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    if not args:
        sys.stderr.write("android_scan: give at least one .kt file or a folder.\n")
        return 2
    skipped, findings, scanned = [], [], 0
    for disp, real, parts in collect(args, skipped):
        raw, reason = read_file(real)
        if raw is None:
            skipped.append({"file": disp, "reason": reason})
        elif is_test_path(parts):
            skipped.append({"file": disp, "reason": "test file"})
        elif is_generated(raw):
            skipped.append({"file": disp, "reason": "generated file"})
        else:
            scanned += 1
            for f in scan_text(raw, parts):
                f["file"] = disp
                findings.append(f)
    if scanned == 0 and not findings:
        sys.stderr.write("android_scan: no readable .kt file to scan in: %s\n" % " ".join(args))
        return 2
    findings.sort(key=lambda f: (f["file"], f["line"], f["rule"]))
    counts = {}
    for f in findings:
        counts[f["rule"]] = counts.get(f["rule"], 0) + 1
    report = {
        "schema_version": SCHEMA_VERSION,
        "tool": TOOL,
        "files_scanned": scanned,
        "findings": [{k: f[k] for k in ("file", "line", "rule", "severity", "confidence",
                                        "match", "why", "fix")} for f in findings],
        "counts_by_rule": dict(sorted(counts.items())),
        "summary": {"warn": sum(1 for f in findings if f["severity"] == "warn"),
                    "info": sum(1 for f in findings if f["severity"] == "info")},
        "skipped": skipped,
        "limits": LIMITS,
    }
    sys.stdout.write(json.dumps(report, indent=1, ensure_ascii=True) + "\n")
    return 1 if report["summary"]["warn"] else 0


if __name__ == "__main__":
    sys.exit(main())
