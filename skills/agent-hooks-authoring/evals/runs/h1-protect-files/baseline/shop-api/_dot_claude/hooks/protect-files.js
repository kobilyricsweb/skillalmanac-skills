// PreToolUse hook: blocks agent edits to .env files, anything under migrations/,
// and package-lock.json. Plain Node so it behaves the same on macOS, Linux and
// Windows (Git Bash). Exit code 2 = block; the stderr text is shown to the agent.
let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => (raw += c));
process.stdin.on('end', () => {
  let input;
  try {
    input = JSON.parse(raw);
  } catch (e) {
    console.error('protect-files: could not parse hook input; blocking to be safe.');
    process.exit(2);
  }

  const ti = input.tool_input || {};
  const target = ti.file_path || ti.notebook_path || ti.path || '';
  if (!target) process.exit(0);

  // Normalise Windows separators and case so C:\x\Migrations\a.sql is caught too.
  const parts = String(target).replace(/\\/g, '/').toLowerCase().split('/').filter(Boolean);
  const name = parts[parts.length - 1] || '';
  const dirs = parts.slice(0, -1);

  let reason = null;
  if (name === '.env' || (name.startsWith('.env.') && name !== '.env.example')) {
    reason = 'it is an .env file (secrets/config)';
  } else if (dirs.includes('migrations')) {
    reason = 'it is under migrations/ (existing migrations must not be edited)';
  } else if (name === 'package-lock.json') {
    reason = 'package-lock.json is generated by npm';
  }

  if (reason) {
    console.error(
      `Blocked: ${target} is protected because ${reason}. Ask the user to make this change themselves.`
    );
    process.exit(2);
  }
  process.exit(0);
});
