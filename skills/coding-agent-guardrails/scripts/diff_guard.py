#!/usr/bin/env python3
"""Scan a unified diff (stdin or file) for things a coding agent must not slip in.

    git diff HEAD | python diff_guard.py
    python diff_guard.py changes.patch [--task-dirs src,tests]

Prints ONE JSON object: findings (each: rule, file, line, note) and verdict
(CLEAN or REVIEW). Secret values are never printed. Reads only; no network.
Exit 0 = CLEAN, 1 = REVIEW, 2 = usage error.

Rules: removed-test, skip-added (skip/xfail/.only/@Ignore), assertion-removed,
timeout-raised, snapshot-changed, generated-edited (vendored/build/lockfile/
minified or file marked generated), secret-added, hook-bypass (--no-verify),
outside-task (only when --task-dirs is given).
"""
import json
import re
import sys

GEN_PATH = re.compile(r"(^|/)(dist|build|out|vendor|third_party|generated|__generated__|gen|\.next|coverage|node_modules)/"
                      r"|\.min\.(js|css)$|(^|/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|poetry\.lock|uv\.lock|Cargo\.lock|go\.sum|Gemfile\.lock|composer\.lock)$"
                      r"|_pb2\.py$|\.pb\.go$")
GEN_MARK = re.compile(r"do not edit|auto-?generated|@generated|generated by", re.I)
TEST_PATH = re.compile(r"(^|/)(tests?|__tests__|spec)/|(^|/)test_[^/]+$|_test\.\w+$|\.(test|spec)\.\w+$")
SKIP = re.compile(r"@pytest\.mark\.(skip|xfail)|pytest\.skip\(|@unittest\.skip|\bxit\(|\bxdescribe\(|\b(it|test|describe)\.(skip|only)\(|@Ignore|t\.Skip\(|\bxfail\b|#\s*(def test_|assert )", re.I)
ASSERT = re.compile(r"\bassert\w*\b|\bexpect\(|\bt\.(Error|Fatal)|\.should\b")
TEST_DEF = re.compile(r"^\s*(def test_\w+|(it|test)\(|func Test\w+|@Test\b)")
TIMEOUT = re.compile(r"timeout\w*\s*[=:(]\s*\d+|--timeout[ =]\d+|jest\.setTimeout\(\d+|sleep\(\d+", re.I)
BYPASS = re.compile(r"--no-verify|--no-gpg-sign|HUSKY=0|SKIP=\w+")
SECRETS = [re.compile(p) for p in (r"\bAKIA[0-9A-Z]{16}\b", r"-----BEGIN (?:[A-Z]+ )*PRIVATE KEY", r"\bsk-[A-Za-z0-9_-]{20,}",
                                   r"\bgh[pousr]_[A-Za-z0-9]{36,}", r"\bxox[abprs]-[A-Za-z0-9-]{10,}")]
PASSWORD = re.compile(r"(?i)\b(password|passwd|secret|api[_-]?key|token)\b[\"']?\s*[:=]\s*[\"']?([^\s\"',;]{8,})")
PLACEHOLDER = re.compile(r"^(changeme|placeholder|example|your|xxx|\*|<|\$\{|\{\{|%|none|null|true|false|test$|process\.env|os\.environ|getenv)", re.I)
SNAP = re.compile(r"\.snap$|__snapshots__/|snapshots?/")


def scan(lines, task_dirs=()):
    out, cur, ln = [], None, 0
    seen_gen = set()
    removed_defs, added_defs = {}, {}

    def add(rule, line, note):
        out.append({"rule": rule, "file": cur, "line": line, "note": note})

    for raw in lines:
        raw = raw.rstrip("\n")
        if raw.startswith("+++ "):
            cur = raw[4:].strip()
            cur = cur[2:] if cur.startswith("b/") else cur
            if cur == "/dev/null":
                cur = None
            elif cur:
                if GEN_PATH.search(cur) and cur not in seen_gen:
                    seen_gen.add(cur)
                    add("generated-edited", 0, "path is vendored/build/lockfile/minified: edit the source and re-run the generator")
                if task_dirs and not any(cur.startswith(d.rstrip("/") + "/") or cur == d for d in task_dirs):
                    add("outside-task", 0, "file is outside the declared task directories")
            continue
        if raw.startswith("--- "):
            old = raw[4:].strip()
            old = old[2:] if old.startswith("a/") else old
            cur = old if old != "/dev/null" else cur
            continue
        m = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)", raw)
        if m:
            ln = int(m.group(1)) - 1
            continue
        if raw.startswith("+") and not raw.startswith("+++"):
            ln += 1
            body = raw[1:]
            if cur and TEST_PATH.search(cur) and SKIP.search(body):
                add("skip-added", ln, "skip/xfail/only/commented-out test added")
            if cur and TEST_PATH.search(cur) and TIMEOUT.search(body):
                add("timeout-raised", ln, "timeout or sleep changed in a test: confirm it is not hiding a hang")
            if cur and SNAP.search(cur):
                add("snapshot-changed", ln, "snapshot edited: confirm the new output is intended, not just green")
            if BYPASS.search(body):
                add("hook-bypass", ln, "hook or signing bypass")
            hit = any(r.search(body) for r in SECRETS)
            pm = PASSWORD.search(body)
            if hit or (pm and not PLACEHOLDER.match(pm.group(2))):
                add("secret-added", ln, "credential-looking value added (value not shown)")
            if cur and TEST_DEF.match(body):
                added_defs[cur] = added_defs.get(cur, 0) + 1
        elif raw.startswith("-") and not raw.startswith("---"):
            body = raw[1:]
            if cur and TEST_PATH.search(cur):
                if TEST_DEF.match(body):
                    removed_defs[cur] = removed_defs.get(cur, 0) + 1
                elif ASSERT.search(body):
                    add("assertion-removed", ln, "assertion removed or rewritten: confirm it was wrong, not inconvenient")
        elif raw.startswith(" "):
            ln += 1
    for f, n in removed_defs.items():
        if n > added_defs.get(f, 0):
            out.append({"rule": "removed-test", "file": f, "line": 0, "note": "%d test definition(s) removed, %d added" % (n, added_defs.get(f, 0))})
    return out


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    task_dirs = ()
    for i, a in enumerate(argv):
        if a == "--task-dirs" and i + 1 < len(argv):
            task_dirs = tuple(d for d in argv[i + 1].split(",") if d)
            args = [x for x in args if x != argv[i + 1]]
        elif a.startswith("--task-dirs="):
            task_dirs = tuple(d for d in a.split("=", 1)[1].split(",") if d)
    try:
        data = open(args[0], encoding="utf-8", errors="replace").read() if args else sys.stdin.read()
    except OSError as e:
        print(json.dumps({"error": str(e)}))
        return 2
    findings = scan(data.splitlines(), task_dirs)
    print(json.dumps({"verdict": "REVIEW" if findings else "CLEAN", "count": len(findings), "findings": findings}, indent=1))
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
